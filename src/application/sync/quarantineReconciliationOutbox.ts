import type { SyncOutbox } from '../../domain/models'
import type { ProjectFreakDatabase } from '../../data/db/projectFreakDb'
import { create_audit_event } from '../../data/repositories/persistenceUtils'
import { is_dangerous_feedback_deletion } from './syncSafetyGate'

type FeedbackType = 'exercise_metrics' | 'readiness_entry'

function parent_key(entry: SyncOutbox): string | null {
  if (entry.entity_type !== 'exercise_metrics' &&
      entry.entity_type !== 'readiness_entry') return null
  const payload = entry.payload_json
  if (!payload || typeof payload !== 'object' || Array.isArray(payload)) {
    return null
  }
  const field = entry.entity_type === 'exercise_metrics'
    ? 'session_exercise_id'
    : 'completed_session_id'
  const value = payload[field]
  return typeof value === 'string' && value.length > 0
    ? `${entry.entity_type}:${value}`
    : null
}

export function is_sendable_mutation(entry: SyncOutbox): boolean {
  return entry.synced_at === null && entry.quarantined_at == null
}

/**
 * Preserves previously unsent one-to-one tombstones and companion upserts as
 * forensic evidence, rather than uploading mutations generated by the
 * duplicate-ID reconciliation loop. Only target a logical parent if at least
 * one pending delete exists. All changes + audit are atomic and idempotent.
 *
 * This is deliberately NOT a generic conflict auto-resolution engine:
 * application data remains untouched, with server canonical recovery handled
 * separately. No records are marked as acknowledged by the cloud.
 */
export async function quarantine_feedback_reconciliation_outbox(
  db: ProjectFreakDatabase,
  at: string,
): Promise<number> {
  return db.transaction('rw', db.sync_outbox, db.audit_events, async () => {
    const pending = await db.sync_outbox
      .filter(is_sendable_mutation)
      .toArray()

    const suspicious_parents = new Set(
      pending.filter(is_dangerous_feedback_deletion)
        .map(parent_key)
        .filter((key): key is string => key !== null),
    )
    if (suspicious_parents.size === 0) return 0

    let quarantined = 0
    for (const entry of pending) {
      const key = parent_key(entry)
      if (key === null || !suspicious_parents.has(key)) continue

      const kind = entry.entity_type as FeedbackType
      const table = kind === 'exercise_metrics'
        ? db.exercise_metrics : db.readiness_entries
      // The entity may already have been removed locally by the old merge.
      // The serialized outbox payload remains valid audit evidence.
      const raw = entry.payload_json
      if (!raw || typeof raw !== 'object' || Array.isArray(raw) ||
          typeof raw.id !== 'string') {
        throw new Error('Unsafe reconciliation outbox payload; sync remains paused.')
      }
      const original = await db.sync_outbox.get(entry.id)
      if (!original || !is_sendable_mutation(original)) continue

      // create_audit_event expects a standard entity envelope. Preserve the
      // *entire* outbox entry in the before-image, including payload/revision.
      const snapshot = (await table.get(entry.entity_id)) ??
        raw as never
      const audit = create_audit_event(
        kind,
        snapshot,
        original,
        'sync_conflict',
      )
      audit.reason = `Quarantined legacy one-to-one ${entry.operation} mutation ${entry.id}. Retained in outbox; never acknowledged or uploaded.`
      audit.created_at = at
      await db.audit_events.add(audit)
      await db.sync_outbox.put({
        ...original,
        quarantined_at: at,
        quarantine_reason: 'Legacy duplicate-ID feedback reconciliation',
      })
      quarantined++
    }
    return quarantined
  })
}
